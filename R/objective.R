# ==============================================================================
# ETVAR objective function
# ==============================================================================

#' ETVAR objective function
#'
#' Given a vector of target-direction angles, this function constructs the
#' target direction and evaluates its event-date contribution. The target path
#' is represented as precomputed quadratic forms in the direction vector, so a
#' complete historical decomposition is not required for each evaluation.
#'
#' The optimiser minimises this function to find the rotation that makes the
#' target shock best explain the event-date movements. [etvar_optimize()]
#' prepares the direction-independent quantities once and reuses them throughout
#' all optimisation stages and starting points.
#'
#' @param theta Numeric vector. Target-direction angles of length `n - 1`.
#'   For backward compatibility, full Euler angles of length `n*(n-1)/2` are
#'   also accepted when `parameterization = "auto"` or `"full"`.
#' @param var_est     An `etvar_var` object from [estimate_var()].
#' @param target_obs  Integer or integer vector. Row index (indices) of the
#'                    event date(s) in the effective sample (i.e., in
#'                    `var_est$Y`). Passing multiple indices defines a target
#'                    window: the objective is the sum across all event dates.
#' @param shock_index Integer. Which structural shock to target. Default 1.
#' @param parameterization Character. Interpretation of `theta`: `"target"`
#'   for the new target-direction angles, `"full"` for legacy full Euler
#'   angles, or `"auto"` to infer from the vector length. In the ambiguous
#'   two-variable case, `"auto"` selects `"target"`.
#' @return Scalar. Sum of absolute scaled deviations across all target dates
#'   (lower is better).
#' @examples
#' set.seed(1)
#' y <- matrix(rnorm(300), ncol = 3)
#' var_est <- estimate_var(y, lags = 2, nimp_wold = 10)
#' # Event on raw row 80, i.e. effective-sample row 80 - lags
#' etvar_objective(c(0, 0), var_est, target_obs = 78)
#' etvar_objective(c(0.5, -0.3), var_est, target_obs = 78)
#' @export
etvar_objective <- function(theta, var_est, target_obs, shock_index = 1L,
                            parameterization = c("auto", "target", "full")) {
  parameterization <- match.arg(parameterization)
  context <- .etvar_prepare_objective(var_est, target_obs, shock_index)
  .etvar_objective_prepared(theta, context, parameterization)
}


# Build the baseline path generated by initial conditions and deterministic
# regressors. This is the same recursion used by hist_decomposition(), without
# constructing any shock-specific paths.
.etvar_deterministic_path <- function(var_est) {
  n <- var_est$n
  lags <- var_est$lags
  trend <- var_est$trend
  constant <- var_est$constant
  X <- var_est$X
  ALPHA <- var_est$ALPHA
  T_raw <- nrow(var_est$Y) + lags

  deterministic <- matrix(0, nrow = T_raw, ncol = n)
  n_constant <- as.integer(constant == 1L)
  n_deterministic <- n_constant + trend

  # Recover the actual pre-sample lag values from the first regressor row.
  for (i_lag in seq_len(lags)) {
    idx_end <- (lags - (i_lag - 1L)) * n + n_deterministic
    idx_start <- idx_end - n + 1L
    deterministic[i_lag, ] <- X[1L, idx_start:idx_end]
  }

  for (raw_time in seq.int(lags + 1L, T_raw)) {
    lag_values <- numeric(lags * n)
    for (lag_i in seq_len(lags)) {
      idx_start <- 1L + (lag_i - 1L) * n
      idx_end <- lag_i * n
      lag_values[idx_start:idx_end] <- deterministic[raw_time - lag_i, ]
    }

    effective_time <- raw_time - lags
    regressor <- .build_reg_vec(
      constant = constant,
      trend = trend,
      tt = effective_time,
      tt2 = effective_time^2,
      auxi = lag_values
    )
    deterministic[raw_time, ] <- drop(
      matrix(regressor, nrow = 1L) %*% ALPHA
    )
  }

  deterministic
}


# Prepare all quantities that do not depend on the candidate target direction.
# For each raw time t and output variable j, coefficient_history[t, j, ]
# represents a matrix M_{t,j} such that the target contribution is q' M q.
.etvar_prepare_objective <- function(var_est, target_obs, shock_index = 1L) {
  if (!inherits(var_est, "etvar_var")) {
    stop("`var_est` must be an `etvar_var` object from `estimate_var()`.",
         call. = FALSE)
  }

  n <- var_est$n
  lags <- var_est$lags
  data <- var_est$data
  shock_index <- .etvar_integer_scalar(shock_index, "shock_index",
                                        min = 1L, max = n)
  target_obs <- .etvar_index_vector(target_obs, "target_obs", nrow(var_est$Y))

  real_diff <- diff(data)
  scales <- apply(real_diff, 2L, stats::sd)
  if (any(!is.finite(scales)) ||
      any(scales <= sqrt(.Machine$double.eps))) {
    stop("Every variable must have non-zero finite first-difference ",
         "variability.", call. = FALSE)
  }

  deterministic <- .etvar_deterministic_path(var_est)
  deterministic_diff <- diff(deterministic)
  diff_indices <- target_obs + lags - 1L
  baseline_scaled <- sweep(
    deterministic_diff[diff_indices, , drop = FALSE] -
      real_diff[diff_indices, , drop = FALSE],
    2L,
    scales,
    "/"
  )

  # Whitened reduced-form residuals z_t = L^{-1} u_t, stored by rows.
  upper_cholesky <- chol(var_est$SIGMA)
  lower_cholesky <- t(upper_cholesky)
  whitened_residuals <- var_est$residuals %*% solve(upper_cholesky)

  n_quadratic <- n * n
  n_events <- length(target_obs)
  event_raw_rows <- target_obs + lags
  event_coefficients_scaled <- array(
    0,
    dim = c(n_events, n, n_quadratic)
  )

  # Only p previous coefficient matrices are needed for the VAR recursion.
  # A circular buffer avoids allocating an O(T * n^3) history array.
  buffer_size <- lags + 1L
  coefficient_buffer <- array(
    0,
    dim = c(buffer_size, n, n_quadratic)
  )
  buffer_slot <- function(raw_time) {
    ((raw_time - 1L) %% buffer_size) + 1L
  }

  n_deterministic <- var_est$constant + var_est$trend
  lag_transitions <- vector("list", lags)
  for (lag_i in seq_len(lags)) {
    rows <- n_deterministic + (lag_i - 1L) * n + seq_len(n)
    lag_transitions[[lag_i]] <- t(
      var_est$ALPHA[rows, , drop = FALSE]
    )
  }

  # Repeating L by residual coordinate creates columns indexed by (a, b),
  # matching as.vector(q %o% q): L[j, a] * z_t[b].
  expanded_cholesky <- lower_cholesky[
    , rep(seq_len(n), times = n), drop = FALSE
  ]

  for (raw_time in seq.int(lags + 1L, max(event_raw_rows))) {
    current <- matrix(0, nrow = n, ncol = n_quadratic)
    for (lag_i in seq_len(lags)) {
      previous <- matrix(
        coefficient_buffer[buffer_slot(raw_time - lag_i), , ],
        nrow = n,
        ncol = n_quadratic
      )
      current <- current + lag_transitions[[lag_i]] %*% previous
    }

    whitened <- whitened_residuals[raw_time - lags, ]
    innovation <- sweep(
      expanded_cholesky,
      2L,
      rep(whitened, each = n),
      "*"
    )
    current <- current + innovation

    matching_events <- which(event_raw_rows == raw_time)
    if (length(matching_events)) {
      previous_time <- matrix(
        coefficient_buffer[buffer_slot(raw_time - 1L), , ],
        nrow = n,
        ncol = n_quadratic
      )
      change_scaled <- sweep(current - previous_time, 1L, scales, "/")
      for (event_i in matching_events) {
        event_coefficients_scaled[event_i, , ] <- change_scaled
      }
    }

    coefficient_buffer[buffer_slot(raw_time), , ] <- current
  }

  structure(
    list(
      n = n,
      shock_index = shock_index,
      target_obs = target_obs,
      baseline_scaled = baseline_scaled,
      event_coefficients_scaled = event_coefficients_scaled,
      scales = scales
    ),
    class = "etvar_objective_context"
  )
}


# Evaluate a candidate using a prepared context. This is the hot path called
# by optim(), so it performs only direction construction and small quadratic
# forms at the target dates.
.etvar_objective_prepared <- function(
    theta,
    context,
    parameterization = c("auto", "target", "full")) {
  if (!inherits(context, "etvar_objective_context")) {
    stop("`context` must be prepared by `.etvar_prepare_objective()`.",
         call. = FALSE)
  }
  parameterization <- match.arg(parameterization)
  n <- context$n
  shock_index <- context$shock_index

  target_angles <- .etvar_prepare_target_start(
    theta, n, shock_index, parameterization
  )
  direction <- .etvar_direction_from_angles(
    target_angles, n, shock_index
  )
  quadratic_terms <- as.vector(tcrossprod(direction))

  discrepancies <- context$baseline_scaled
  for (event_i in seq_len(nrow(discrepancies))) {
    coefficients <- matrix(
      context$event_coefficients_scaled[event_i, , ],
      nrow = n,
      ncol = n * n
    )
    discrepancies[event_i, ] <- discrepancies[event_i, ] +
      drop(coefficients %*% quadratic_terms)
  }

  sum(abs(discrepancies))
}
